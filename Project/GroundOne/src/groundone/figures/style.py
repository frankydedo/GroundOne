"""Shared figure style for the thesis (static PNG, light surface, print-friendly).

Colours follow a validated categorical palette (dataviz skill reference palette, fixed order, CVD-checked) and are
assigned to *entities*, never to ranks: a system has the same colour in every figure.
Every figure is saved as PNG (300 dpi) together with a caption in the group's index.md.
"""
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from ..config import PROJECT  # noqa: E402

FIG_ROOT = PROJECT / "figures"
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7", "#e34948"]
NEUTRAL = "#9a9890"

# fixed entity -> colour (identity), shared by every figure
SYSTEM_COLORS = {
    "GroundOne 0.5B": SERIES[0], "GroundOne 3B": SERIES[6],
    "Untrained 0.5B": NEUTRAL, "Untrained 3B": "#6e6c66",
    "MiniCheck-RoBERTa": SERIES[1], "MiniCheck-DeBERTa": SERIES[4], "HHEM": SERIES[2],
    "Rizzo-Flow 4B": SERIES[3], "Terse judge": SERIES[7], "Verbose judge": SERIES[5],
    "System One (batched)": SERIES[0], "System One (sequential)": SERIES[4],
}

plt.rcParams.update({
    "figure.dpi": 110, "savefig.dpi": 300, "figure.facecolor": SURFACE, "axes.facecolor": SURFACE,
    "axes.edgecolor": INK2, "axes.labelcolor": INK, "text.color": INK, "xtick.color": INK2, "ytick.color": INK2,
    "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
    "axes.axisbelow": True, "font.size": 9, "axes.titlesize": 10, "axes.titleweight": "bold", "legend.frameon": False,
    "lines.linewidth": 2, "lines.markersize": 6,
})


class Group:
    """A folder of figures (figures/<name>/) with an index.md of captions."""

    def __init__(self, name):
        self.dir = FIG_ROOT / name
        self.dir.mkdir(parents=True, exist_ok=True)
        self.items = []

    def save(self, fig, stem, caption, source):
        fig.tight_layout()
        fig.savefig(self.dir / f"{stem}.png", bbox_inches="tight", facecolor=SURFACE)
        plt.close(fig)
        self.items.append({"file": f"{stem}.png", "caption": caption, "source": source})
        print(f"  saved figures/{self.dir.name}/{stem}.png", flush=True)

    def write_index(self, title):
        lines = [f"# {title}", "", "Generated by `groundone figures`; regenerate after new results. Captions are drafts for the thesis.", ""]
        for it in self.items:
            lines += [f"## {it['file']}", "", f"![]({it['file']})", "", it["caption"], "", f"*Source: {it['source']}*", ""]
        (self.dir / "index.md").write_text("\n".join(lines))
        (self.dir / "index.json").write_text(json.dumps(self.items, indent=2))


def bar_labels(ax, bars, fmt="{:.2f}", inside=False):
    for b in bars:
        h = b.get_height()
        if h != h:  # NaN
            continue
        ax.annotate(fmt.format(h), (b.get_x() + b.get_width() / 2, h), xytext=(0, 2), textcoords="offset points",
                    ha="center", va="bottom", fontsize=7, color=INK2)


def load_json(path):
    p = Path(path)
    return json.loads(p.read_text()) if p.exists() else None
